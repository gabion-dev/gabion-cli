#!/usr/bin/env node

// src/install.ts

import { createHash } from "crypto";
import { spawnSync } from "child_process";
import {
  copyFileSync,
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "fs";
import { join } from "path";
import { tmpdir } from "os";
import { readAuthConfig } from "./config.js";
import { requestRuntimeDownload, ApiError, formatTokenError } from "./api-client.js";
import {
  ARCHIVE_PREFIX,
  ENGINES_DIR,
  GABION_HOME,
  GRADLE_SOURCE_ENGINES,
  HEADLESS_ENGINE,
  RUNTIME_DIR,
  TEMPLATE_DIR,
  VERSION_JSON_PATH,
} from "./constants.js";
import type { DownloadResponse, RuntimeDownloadResult } from "./types.js";

function logStep(step: number, total: number, message: string): void {
  console.log(`\n→ [${String(step)}/${String(total)}] ${message}`);
}

function fail(message: string): number {
  console.error(`\ngabion install: ${message}`);
  return 1;
}

function isDownloadResponse(
  result: RuntimeDownloadResult,
): result is DownloadResponse {
  return "url" in result;
}

function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${String(bytes)} B`;
  const kb = bytes / 1024;
  if (kb < 1024) return `${kb.toFixed(1)} KB`;
  const mb = kb / 1024;
  return `${mb.toFixed(1)} MB`;
}

async function downloadFile(url: string, destPath: string): Promise<void> {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`Download failed: HTTP ${String(response.status)}`);
  }

  const totalStr = response.headers.get("content-length");
  const totalBytes = totalStr !== null ? parseInt(totalStr, 10) : 0;
  const reader = response.body?.getReader();
  if (reader === undefined) {
    throw new Error("No response body");
  }

  const chunks: Uint8Array[] = [];
  let receivedBytes = 0;

  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    chunks.push(value);
    receivedBytes += value.length;

    if (totalBytes > 0) {
      const pct = Math.round((receivedBytes / totalBytes) * 100);
      process.stdout.write(
        `\r\x1B[K   Downloading... ${String(pct)}% (${formatBytes(receivedBytes)} / ${formatBytes(totalBytes)})`,
      );
    } else {
      process.stdout.write(
        `\r\x1B[K   Downloading... ${formatBytes(receivedBytes)}`,
      );
    }
  }
  process.stdout.write("\n");

  writeFileSync(destPath, Buffer.concat(chunks));
}

function verifySha256(filePath: string, expected: string): void {
  const hash = createHash("sha256");
  hash.update(readFileSync(filePath));
  const actual = hash.digest("hex");
  if (actual !== expected) {
    throw new Error(
      `SHA-256 mismatch: expected ${expected}, got ${actual}`,
    );
  }
}

function extractTarGz(archivePath: string, destDir: string): void {
  const result = spawnSync("tar", ["-xzf", archivePath, "-C", destDir], {
    stdio: "inherit",
  });
  if (result.status !== 0) {
    throw new Error("tar extraction failed");
  }
}

/**
 * Approve the install script of esbuild (the one trusted runtime dependency
 * with a postinstall script) by writing allowScripts into the runtime
 * manifest BEFORE dependencies are installed.
 */
function approveRuntimeScripts(runtimeDir: string): void {
  const manifestPath = join(runtimeDir, "package.json");
  const raw: unknown = JSON.parse(readFileSync(manifestPath, "utf-8"));
  if (typeof raw !== "object" || raw === null) return;
  const manifest = raw as Record<string, unknown>;
  manifest["allowScripts"] = { esbuild: true };
  writeFileSync(
    manifestPath,
    `${JSON.stringify(manifest, null, 2)}\n`,
    "utf-8",
  );
}

/**
 * Copy engine SOURCE code from the extracted archive into the installed
 * engines directory. Gradle source engines are wiped and re-copied (their
 * build output is regenerated by --post-download). Headless source files
 * are merged with cpSync so binary artifacts (browser/, lib/) survive.
 * Binary-only engines (gitleaks, mailpit, etc.) are not in the archive and
 * are untouched.
 */
function copyEngineSourcesFromArchive(
  archiveEngines: string,
  destEngines: string,
): void {
  if (!existsSync(archiveEngines)) return;
  mkdirSync(destEngines, { recursive: true });

  for (const engine of GRADLE_SOURCE_ENGINES) {
    const src = join(archiveEngines, engine);
    const dest = join(destEngines, engine);
    if (!existsSync(src)) continue;
    if (existsSync(dest)) {
      rmSync(dest, { recursive: true, force: true });
    }
    cpSync(src, dest, { recursive: true });
  }

  const headlessSrc = join(archiveEngines, HEADLESS_ENGINE);
  const headlessDest = join(destEngines, HEADLESS_ENGINE);
  if (existsSync(headlessSrc)) {
    mkdirSync(headlessDest, { recursive: true });
    cpSync(headlessSrc, headlessDest, { recursive: true, force: true });
  }
}

/**
 * Core download-and-install logic shared between `gabion install` and
 * `gabion self-update`. Downloads the archive, unpacks it, installs
 * npm dependencies, and delegates remaining build steps to the full CLI
 * via `install --post-download`.
 */
export async function downloadAndInstall(
  download: DownloadResponse,
): Promise<number> {
  const totalSteps = 8;
  const { version, url, sha256 } = download;

  logStep(1, totalSteps, `Downloading runtime v${version}`);
  const tempDir = mkdtempSync(join(tmpdir(), "gabion-"));

  try {
    const archiveName = `${ARCHIVE_PREFIX}-${version}.tar.gz`;
    const archivePath = join(tempDir, archiveName);
    await downloadFile(url, archivePath);

    logStep(2, totalSteps, "Verifying SHA-256 checksum");
    verifySha256(archivePath, sha256);
    console.log("   Checksum OK");

    logStep(3, totalSteps, "Extracting archive");
    extractTarGz(archivePath, tempDir);
    const archiveRoot = join(tempDir, `${ARCHIVE_PREFIX}-${version}`);

    if (!existsSync(join(archiveRoot, "runtime"))) {
      return fail("archive missing runtime/ directory");
    }

    logStep(4, totalSteps, "Installing runtime files");
    mkdirSync(GABION_HOME, { recursive: true });

    if (existsSync(RUNTIME_DIR)) {
      rmSync(RUNTIME_DIR, { recursive: true, force: true });
    }
    cpSync(join(archiveRoot, "runtime"), RUNTIME_DIR, { recursive: true });

    copyEngineSourcesFromArchive(join(archiveRoot, ".engines"), ENGINES_DIR);

    const archiveTemplate = join(archiveRoot, "template");
    if (existsSync(archiveTemplate)) {
      if (existsSync(TEMPLATE_DIR)) {
        rmSync(TEMPLATE_DIR, { recursive: true, force: true });
      }
      cpSync(archiveTemplate, TEMPLATE_DIR, { recursive: true });
    }

    copyFileSync(join(archiveRoot, "version.json"), VERSION_JSON_PATH);

    logStep(5, totalSteps, "Installing runtime dependencies");
    approveRuntimeScripts(RUNTIME_DIR);
    const npmResult = spawnSync("npm", ["install", "--omit=dev"], {
      cwd: RUNTIME_DIR,
      stdio: "inherit",
    });
    if (npmResult.status !== 0) {
      return fail("npm install in runtime failed");
    }

    logStep(6, totalSteps, "Creating workspace symlinks");
    const topNodeModules = join(GABION_HOME, "node_modules");
    rmSync(topNodeModules, { recursive: true, force: true });
    symlinkSync(join(RUNTIME_DIR, "node_modules"), topNodeModules, "junction");

    logStep(7, totalSteps, "Finalizing installation");
    const cliEntry = join(RUNTIME_DIR, "cli", "gabion.ts");
    const env: Record<string, string> = {
      ...process.env as Record<string, string>,
      GABION_ORIGINAL_CWD: process.cwd(),
    };
    const postResult = spawnSync(
      process.execPath,
      ["--import", "tsx", cliEntry, "install", "--post-download"],
      { stdio: "inherit", cwd: RUNTIME_DIR, env },
    );
    if (postResult.status !== 0) {
      return fail("post-download finalization failed");
    }

    logStep(8, totalSteps, "Done");
    return 0;
  } finally {
    rmSync(tempDir, { recursive: true, force: true });
  }
}

export async function runInstall(_args: readonly string[]): Promise<number> {
  const auth = readAuthConfig();
  if (auth === null) {
    console.error(
      "Gabion requires an access token to download the runtime.\n\n" +
      "  1. Get your token from the project author\n" +
      "  2. Authenticate:\n\n" +
      "       gabion auth YOUR_TOKEN\n\n" +
      "  3. Then re-run:\n\n" +
      "       gabion install\n",
    );
    return 1;
  }

  console.log("gabion install — downloading and installing Gabion runtime\n");

  const currentVersion = null;

  let result: RuntimeDownloadResult;
  try {
    result = await requestRuntimeDownload(
      auth.token,
      currentVersion,
      auth.apiUrl,
    );
  } catch (err: unknown) {
    if (err instanceof ApiError && err.reason !== "") {
      console.error(`\n✖ ${formatTokenError(err)}`);
      return 1;
    }
    return fail(
      `API request failed: ${err instanceof Error ? err.message : String(err)}`,
    );
  }

  if (!isDownloadResponse(result)) {
    console.log("Runtime is already up to date.");
    return 0;
  }

  return downloadAndInstall(result);
}